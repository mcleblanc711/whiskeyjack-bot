"""T-901 acceptance: golden schema fixtures for binary, multiple-choice and numeric records.

Backlog row: *"Add valid/invalid binary, multiple-choice and numeric records"*, acceptance
criterion *"Fixtures cover all required fields, bounds and malformed outputs."*
``CODEX_HANDOFF.md``'s "Schema tests" bullets are the literal spec this file discharges:

- valid golden records for binary, multiple-choice and numeric;
- malformed model outputs rejected;
- unknown fields either rejected or explicitly versioned.

Its fourth bullet, *"database migration from empty file is deterministic"*, is already fully
covered by ``tests/unit/test_ledger.py`` (``test_schema_is_deterministic``,
``test_migration_is_idempotent``, M1-601) and is intentionally not duplicated here.

**Authored blind** (``docs/TRACKS.md`` Wave 11's owner-split note): built only from
``CODEX_HANDOFF.md``'s test requirements, ``prompts/forecaster.md`` (the model-facing contract
``forecast/schema.py`` is transcribed from), ``questions/model.py`` (M1-201),
``forecast/schema.py`` and ``forecast/attribution.py`` (M1-402/M1-501), and
``forecast/validate.py``'s public ``output_problems`` signature. Deliberately not read:
``forecast/binary.py``, ``forecast/numeric.py``, ``forecast/multiple_choice.py`` or their test
files -- those own the type-specific bound rules (percentile-level exactness, option-set
matching, the binary prior requirement), so this suite reaches them only through
``output_problems`` and asserts a non-empty problem list, never the exact wording.

Required-field and blank-string coverage is generated by introspecting each pydantic model's
own ``model_fields`` against the golden fixture, rather than hand-picking cases -- so a field
added to a schema later is covered automatically instead of silently escaping this suite.
"""

