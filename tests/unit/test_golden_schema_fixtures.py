def test_output_problems_refuses_a_source_ids_argument_of_the_wrong_shape() -> None:
    """``attribution.py``'s own docstring names this: a bare string satisfies ``Sequence[str]``
    and would silently mean "the ids are each one character of this string"."""
    forecast = validate_forecast_response(_response_golden("binary"), BinaryForecastResponse)
    question = CanonicalBinaryQuestion(**_question_golden("binary"))
