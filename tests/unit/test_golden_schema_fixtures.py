def test_the_required_field_walk_is_not_vacuous() -> None:
    """LESSONS.md's guard: an empty coverage set would make every test below pass for the
    wrong reason. Pin the load-bearing fields this suite depends on being found."""
    for qtype in QUESTION_TYPES:
        paths = set(_question_required_paths(qtype))
        assert {"question_id", "post_id", "title"} <= paths
    assert "options" in set(_question_required_paths("multiple_choice"))
    numeric_question_paths = set(_question_required_paths("numeric"))
    assert {
        "lower_bound",
        "upper_bound",
        "open_lower_bound",
        "open_upper_bound",
        "cdf_size",
    } <= numeric_question_paths

    shared_response_fields = {
        "schema_version",
        "question_id",
        "as_of_utc",
        "base_rate.reference_class",
        "base_rate.basis",
        "status_quo",
        "rationale_summary",
        "process_confidence",
        "question_type",
        "final_prediction",
    }
    for qtype in QUESTION_TYPES:
        assert shared_response_fields <= set(_response_required_paths(qtype))
    assert "final_prediction.probability_yes" in set(_response_required_paths("binary"))
    mc_response_paths = set(_response_required_paths("multiple_choice"))
    assert {
        "final_prediction.options",
        "final_prediction.options.0.option",
        "final_prediction.options.0.probability",
    } <= mc_response_paths
    numeric_response_paths = set(_response_required_paths("numeric"))
    assert {
        "final_prediction.percentiles",
        "final_prediction.percentiles.0.percentile",
        "final_prediction.percentiles.0.value",
    } <= numeric_response_paths


@pytest.mark.parametrize("qtype", QUESTION_TYPES)
def test_every_required_question_field_is_enforced(qtype: str) -> None:
    golden = _question_golden(qtype)
    paths = _question_required_paths(qtype)
    assert paths, "the walk must find at least one required field to discriminate anything"
    for path in paths:
        mutated = _delete_path(golden, path)
        with pytest.raises(ValidationError):
            QUESTION_MODELS[qtype](**mutated)


@pytest.mark.parametrize("qtype", QUESTION_TYPES)
def test_every_required_response_field_is_enforced(qtype: str) -> None:
    golden = _response_golden(qtype)
    paths = _response_required_paths(qtype)
    assert paths, "the walk must find at least one required field to discriminate anything"
    for path in paths:
        mutated = _delete_path(golden, path)
        with pytest.raises(ForecastSchemaError):
            validate_forecast_response(mutated, RESPONSE_MODELS[qtype])


