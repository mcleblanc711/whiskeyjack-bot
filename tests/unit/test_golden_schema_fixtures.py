def _load_json(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    assert isinstance(data, dict)
    return data


def _question_golden(qtype: str) -> dict[str, Any]:
    return _load_json(QUESTION_FIXTURES / f"{qtype}_golden.json")


def _response_golden(qtype: str) -> dict[str, Any]:
    return _load_json(FORECAST_FIXTURES / f"{qtype}_golden.json")


def _response_sources(qtype: str) -> list[str]:
    ids = _load_json(FORECAST_FIXTURES / f"{qtype}_golden_sources.json")["source_ids"]
    assert isinstance(ids, list)
    return ids


def _committed_forecast_config() -> ForecastConfig:
    """The forecast section of the committed ``config.example.yaml``, not a hand-built one.

    A config this suite built itself could quietly drift from the range the prompt tells the
    model to respect; the committed example is the one an operator actually runs against.
    """
    data = copy.deepcopy(
        yaml.safe_load((REPO_ROOT / "config.example.yaml").read_text(encoding="utf-8"))
    )
    data["model"]["name"] = "openrouter/test-model"
    return validate_config_data(data).forecast


def _model_of(annotation: Any) -> type[BaseModel] | None:
    """The pydantic model reachable from one field annotation, if any (through Optional/list)."""
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    for arg in get_args(annotation):
        found = _model_of(arg)
        if found is not None:
            return found
    return None


def _iter_required_paths(model: type[BaseModel], data: Any, prefix: str = "") -> Iterator[str]:
    """Every required-field JSON path this model declares, checked against real fixture data.

    Recurses into a nested model reached through a bare field, an ``Optional`` or a ``list`` --
    but only into a list's first item, since every item shares the same item schema and walking
    the rest would only multiply the case count, not the coverage.
    """
    if not isinstance(data, dict):
        return
    for name, field in model.model_fields.items():
        path = f"{prefix}{name}"
        if field.is_required():
            yield path
        nested_model = _model_of(field.annotation)
        if nested_model is None:
            continue
        value = data.get(name)
        if isinstance(value, dict):
            yield from _iter_required_paths(nested_model, value, prefix=f"{path}.")
        elif isinstance(value, list) and value:
            yield from _iter_required_paths(nested_model, value[0], prefix=f"{path}.0.")


def _question_required_paths(qtype: str) -> list[str]:
    return sorted(set(_iter_required_paths(QUESTION_MODELS[qtype], _question_golden(qtype))))


def _response_required_paths(qtype: str) -> list[str]:
    return sorted(set(_iter_required_paths(RESPONSE_MODELS[qtype], _response_golden(qtype))))


def _navigate(data: Any, parts: list[str]) -> tuple[Any, str]:
    node = data
    for part in parts[:-1]:
        node = node[int(part)] if part.isdigit() else node[part]
    return node, parts[-1]


def _delete_path(data: dict[str, Any], path: str) -> dict[str, Any]:
    mutated = copy.deepcopy(data)
    node, leaf = _navigate(mutated, path.split("."))
    if leaf.isdigit():
        del node[int(leaf)]
    else:
        del node[leaf]
    return mutated


def _set_path(data: dict[str, Any], path: str, value: Any) -> dict[str, Any]:
    mutated = copy.deepcopy(data)
    node, leaf = _navigate(mutated, path.split("."))
    if leaf.isdigit():
        node[int(leaf)] = value
    else:
        node[leaf] = value
    return mutated


# --- valid golden records ------------------------------------------------------------


@pytest.mark.parametrize("qtype", QUESTION_TYPES)
def test_the_golden_question_validates_and_round_trips(qtype: str) -> None:
    data = _question_golden(qtype)
    question = QUESTION_MODELS[qtype](**data)
    assert question.qtype == qtype
    again = QUESTION_MODELS[qtype].model_validate(question.model_dump(mode="json"))
    assert again == question
    assert CanonicalQuestionAdapter.validate_python(data) == question


@pytest.mark.parametrize("qtype", QUESTION_TYPES)
def test_the_golden_response_validates_and_passes_every_output_check(qtype: str) -> None:
    question = QUESTION_MODELS[qtype](**_question_golden(qtype))
    forecast = validate_forecast_response(_response_golden(qtype), RESPONSE_MODELS[qtype])
    problems = output_problems(
        forecast,
        _committed_forecast_config(),
        question=question,
        source_ids=_response_sources(qtype),
    )
    assert problems == []
    again = RESPONSE_MODELS[qtype].model_validate(forecast.model_dump(mode="json"))
    assert again == forecast


