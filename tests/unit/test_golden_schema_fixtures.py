@pytest.mark.parametrize("qtype", QUESTION_TYPES)
def test_rationale_summary_word_cap_is_enforced(qtype: str) -> None:
    golden = _response_golden(qtype)
    at_cap = " ".join("word" for _ in range(MAX_RATIONALE_WORDS))
    validate_forecast_response({**golden, "rationale_summary": at_cap}, RESPONSE_MODELS[qtype])
